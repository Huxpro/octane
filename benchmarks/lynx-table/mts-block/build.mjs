/**
 * Issue-#163 C0 — assemble the `octane-mts-block` cell.
 *
 * Splices `emit.mjs`'s generated create functions into `runtime.js`, then wraps
 * the result in the same JSON web bundle `prototype/build.mjs` produces, with
 * the same `pageConfig` and the same `app/src/app.css`. Its background program
 * is `prototype/app-service.js`, unchanged and unforked: the cell's whole claim
 * is that the *main-thread* program came from the compiler's lowering, so
 * anything else that differed would spoil the comparison.
 *
 *   node mts-block/derive.mjs         # first: programs.json
 *   node mts-block/build.mjs --rows 1000,10000,30000
 *
 * writes mts-block/dist/main.web.bundle           (empty table, click-driven)
 *        mts-block/dist-rows{N}/main.web.bundle   (mount-create FCP ladder)
 */
import fs from 'node:fs';
import path from 'node:path';
import { parseArgs } from 'node:util';

import { readWebBundleSections } from '../prototype/bundle-tools.mjs';
import { emitProgram, retainedNodes } from './emit.mjs';

const ROOT = import.meta.dirname;
const BENCH = path.resolve(ROOT, '..');

const { values: args } = parseArgs({ options: { rows: { type: 'string', default: '' } } });
const autoRowVariants = args.rows
	.split(',')
	.map((value) => Number(value.trim()))
	.filter(Boolean);

const octaneBundlePath = path.join(BENCH, 'app/dist/main.web.bundle');
if (!fs.existsSync(octaneBundlePath)) {
	throw new Error(
		`Build the octane app first (scripts/build-app.mjs): missing ${octaneBundlePath}`,
	);
}
const programsPath = path.join(ROOT, 'programs.json');
if (!fs.existsSync(programsPath)) {
	throw new Error(`Run mts-block/derive.mjs first: missing ${programsPath}`);
}

const pageConfig = readWebBundleSections(octaneBundlePath).configurations;
const appCss = fs.readFileSync(path.join(BENCH, 'app/src/app.css'), 'utf8');
const runtime = fs.readFileSync(path.join(ROOT, 'runtime.js'), 'utf8');
// A comment rather than a bare token, so `runtime.js` is still a file
// Prettier can parse. Referenced by name below and nowhere else, so the
// file mentions it exactly once and the splice cannot hit a doc comment.
const MARKER = '// @GENERATED@';
const serviceSource = fs.readFileSync(path.join(BENCH, 'prototype/app-service.js'), 'utf8');
const programs = JSON.parse(fs.readFileSync(programsPath, 'utf8'));

// The page's event sites are the toolbar buttons, in the order the program
// declares them, and the background service routes by the same `b:<index>`
// token `prototype/lepus-root.js` mints. Deriving them from the program rather
// than restating a label list is the point: a thirteenth button would appear
// here without anyone editing this file.
const buttonTokens = programs.page.wire.events.map((_event, index) => `b:${index}`);

const rowRetained = retainedNodes(programs.row);
const rowSlots = rowRetained.map((_node, index) => `rowSlot${index}`);
const chromeRetained = retainedNodes(programs.page);
if (chromeRetained.length !== 0) {
	throw new Error(
		`the page program grew ${chromeRetained.length} value slots; the runtime half writes none`,
	);
}

const generated = [
	'\t// ---- generated by mts-block/emit.mjs from mts-block/programs.json ----',
	"\t// Derived from app/src/App.lynx.tsrx by the framework's own plan → wire",
	'\t// lowering. Do not hand-edit: `node mts-block/build.mjs` overwrites it.',
	`\tvar ${rowSlots.map((name) => `${name} = []`).join(', ')};`,
	'',
	emitProgram(programs.page, {
		name: 'createChrome',
		parentExpr: 'page',
		retain: [],
		slotArrays: [],
		tokenPrefixes: buttonTokens,
		prologue: [
			"\t\tpage = __CreatePage('0', 0);",
			'\t\t__SetCSSId([page], 0);',
			'\t\tpageId = __GetElementUniqueID(page);',
		],
		expose: { [programs.page.range.node]: 'rowsParent' },
	}),
	'',
	emitProgram(programs.row, {
		name: 'createRow',
		parentExpr: 'rowsParent',
		retain: rowRetained,
		slotArrays: rowSlots,
	}),
	'\t// ---- end generated ----',
].join('\n');

if (!runtime.includes(MARKER)) throw new Error(`runtime.js lost its ${MARKER} splice point`);
const lepusSource = runtime.replace(MARKER, generated);

function buildVariant(autoRows) {
	const define = (source) => source.replace(/__AUTO_ROWS__/g, String(autoRows));
	return JSON.stringify({
		styleInfo: { 0: { content: [appCss], rules: [] } },
		manifest: { '/app-service.js': define(serviceSource) },
		cardType: pageConfig.cardType ?? 'react',
		appType: 'card',
		pageConfig,
		lepusCode: { root: define(lepusSource) },
		customSections: {},
		elementTemplates: {},
	});
}

fs.writeFileSync(path.join(ROOT, 'lepus-root.generated.js'), lepusSource);
for (const autoRows of [0, ...autoRowVariants]) {
	const dir = path.join(ROOT, autoRows > 0 ? `dist-rows${autoRows}` : 'dist');
	fs.mkdirSync(dir, { recursive: true });
	const outPath = path.join(dir, 'main.web.bundle');
	fs.writeFileSync(outPath, buildVariant(autoRows));
	console.log(`[mts-block] wrote ${path.relative(BENCH, outPath)}`);
}
